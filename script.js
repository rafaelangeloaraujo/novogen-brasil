const getYoutubeId = (url) => {
  const value = String(url || "");
  return value.match(/(?:embed\/|watch\?v=|youtu\.be\/)([A-Za-z0-9_-]{6,})/)?.[1] || "";
};

const ensureVideoModal = () => {
  let modal = document.querySelector("[data-video-modal]");
  if (modal) return modal;

  modal = document.createElement("div");
  modal.className = "video-modal";
  modal.setAttribute("data-video-modal", "");
  modal.innerHTML = `
    <div class="video-modal-dialog" role="dialog" aria-modal="true" aria-label="Video Novocenter">
      <button class="video-modal-close" type="button" aria-label="Fechar vídeo" data-video-close>&times;</button>
      <div class="video-modal-frame" data-video-frame></div>
    </div>
  `;
  document.body.appendChild(modal);

  const close = () => {
    modal.classList.remove("open");
    modal.querySelector("[data-video-frame]").innerHTML = "";
    document.body.classList.remove("nav-open");
  };

  modal.querySelector("[data-video-close]").addEventListener("click", close);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) close();
  });
  window.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && modal.classList.contains("open")) close();
  });

  return modal;
};

const openVideoModal = (videoId) => {
  if (!videoId) return;
  const modal = ensureVideoModal();
  const frame = modal.querySelector("[data-video-frame]");
  const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;
  const localNovocenterUrl = localPageUrl("novocenter.html");

  if (window.location.protocol === "file:") {
    frame.innerHTML = `
      <div class="video-modal-fallback">
        <strong>Abra pelo XAMPP para assistir aqui</strong>
        <p>O player interno precisa de um endereço local HTTP. O XAMPP está respondendo nesta máquina; abra a versão local do site para reproduzir os vídeos dentro da página.</p>
        <div class="video-modal-actions">
          <a class="btn primary" href="${localNovocenterUrl}">Abrir pelo XAMPP</a>
          <a class="btn secondary" href="${watchUrl}" target="_blank" rel="noopener">Assistir no YouTube</a>
        </div>
      </div>
    `;
  } else {
    const origin = encodeURIComponent(window.location.origin);
    frame.innerHTML = `
      <iframe title="Video Novocenter" src="https://www.youtube.com/embed/${videoId}?autoplay=1&rel=0&origin=${origin}" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen referrerpolicy="origin-when-cross-origin"></iframe>
    `;
  }

  modal.classList.add("open");
  document.body.classList.add("nav-open");
};

const enhanceNovocenterVideos = () => {
  document.querySelectorAll(".library-card-media iframe[src*='youtube.com/embed/']").forEach((iframe) => {
    const videoId = getYoutubeId(iframe.src);
    if (!videoId) return;
    const title = iframe.title || "Video Novocenter";
    const preview = document.createElement("button");
    preview.className = "video-preview";
    preview.type = "button";
    preview.dataset.videoId = videoId;
    preview.setAttribute("aria-label", `Assistir: ${title}`);
    preview.innerHTML = `
      <img src="https://img.youtube.com/vi/${videoId}/hqdefault.jpg" alt="" loading="lazy">
      <span class="video-preview-play" aria-hidden="true">&#9658;</span>
      <span class="video-preview-title">${escapeHtml(title)}</span>
    `;
    iframe.replaceWith(preview);
  });

  document.querySelectorAll("[data-video-id]").forEach((button) => {
    if (button.dataset.videoReady === "true") return;
    button.dataset.videoReady = "true";
    button.addEventListener("click", () => openVideoModal(button.dataset.videoId));
  });

  document.querySelectorAll("a[href*='youtube.com/watch']").forEach((link) => {
    const videoId = getYoutubeId(link.href);
    if (!videoId) return;
    link.addEventListener("click", (event) => {
      event.preventDefault();
      openVideoModal(videoId);
    });
  });
};

const renderNovocenterLibrary = async () => {
  const library = document.querySelector("[data-novocenter-library]");
  if (!library) return;

  const buttons = document.querySelectorAll("[data-library-filter], .library-toolbar label[for^='library-filter-']");
  let activeFilter = "all";
  const getFilterFromControl = (control) => {
    if (control.dataset.libraryFilter) return control.dataset.libraryFilter;
    const target = control.getAttribute("for") || "";
    if (target.includes("videos")) return "Vídeos";
    if (target.includes("articles")) return "Artigos";
    if (target.includes("posters")) return "Posters";
    return "all";
  };

  const render = () => {
    library.querySelectorAll(".library-card").forEach((card) => {
      const category = card.dataset.libraryCategory;
      card.hidden = activeFilter !== "all" && category !== activeFilter;
    });
  };

  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      activeFilter = getFilterFromControl(button);
      buttons.forEach((item) => item.classList.toggle("active", getFilterFromControl(item) === activeFilter));
      render();
    });
  });

  render();
};

